def escape_lua_string(s):
    # Current PT texts contain no double quotes or backslashes; keep as a safety net.
    return s.replace('\\', '\\\\').replace('"', '\\"')

def main():
    text = FILE.read_text(encoding="utf-8")
    total = 0
    for boss, pt in PT.items():
        pattern = (
            r'(?s)(\["' + re.escape(boss) + r'"\]\s*=\s*\{\s*order\s*=\s*\d+,\s*type\s*=\s*"BOSS",\s*tips\s*=\s*"[^"]*",)(\s*\},)'
        )
        repl = r'\1\n        tipsByDifficulty = { normal = "' + escape_lua_string(pt) + r'" },\2'
        new_text, count = re.subn(pattern, repl, text, count=1)
        if count == 0:
            print(f"WARN: did not match boss {boss}")
        else:
            total += count
            text = new_text
    FILE.write_text(text, encoding="utf-8")
    print(f"Updated {total} bosses with PT-mode tipsByDifficulty.normal")

if __name__ == "__main__":
    main()
