-- 选择目标语言表：zhTW -> 繁中；enUS/enGB -> 英语；其余 -> 简中
local selected
if locale == "zhTW" then
    selected = L_zhTW
elseif locale == "enUS" or locale == "enGB" then
    selected = L_enUS
else
    selected = L_zhCN
end

-- 暴露给其余文件的当前语言标识
addon.LOCALE = (locale == "zhTW") and "zhTW"
                or ((locale == "enUS" or locale == "enGB") and "enUS")
                or "zhCN"

-- 元表：selected[k] -> L_zhCN[k] -> k（三层回退，保证未翻译 key 至少有中文兜底，再退 key 本身便于调试）
addon.L = setmetatable({}, {
    __index = function(t, k)
        local v = selected[k]
        if v == nil then v = L_zhCN[k] end
        if v == nil then v = k end
        return v
    end
})
